"""Audit/regenerate the committed GA@2 dB fixtures; not run by examples."""
from pathlib import Path
import csv
import json
import math

ROOT = Path(__file__).resolve().parents[1]


def log_phi(x):
    if x <= 10:
        return min(0.0, -0.4527 * x ** .86 + .0218)
    return .5 * math.log(math.pi / x) - x / 4 + math.log1p(-10 / (7 * x))


def bad_mean(x):
    lp = log_phi(x)
    target = lp + math.log(2 - math.exp(lp))
    lo, hi = 0.0, x
    for _ in range(80):
        mid = (lo + hi) / 2
        if log_phi(mid) > target:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def ga(n, k, ebn0=2.0):
    means = [4 * (k / n) * 10 ** (ebn0 / 10)]
    while len(means) < n:
        means = [value for x in means for value in (bad_mean(x), 2 * x)]
    return sorted(sorted(range(n), key=lambda j: (means[j], j), reverse=True)[:k]), means


def main():
    information, patterns, fixture = {}, {}, {}
    for n in (64, 128, 256):
        info, means = ga(n, n // 2)
        information[n] = info
        patterns[n] = {
            "none": {"punctured": [], "shortened": []},
            "puncture": {"punctured": list(range(n // 16)), "shortened": []},
            "shorten": {"punctured": [], "shortened": list(range(n - n // 16, n))},
            "mixed": {"punctured": list(range(n // 32)), "shortened": list(range(n - n // 32, n))}
        }
        for kind in ("polar", "pac"):
            fixture[f"{kind}_{n}_{n//2}"] = dict(n=n, k=n//2, kind=kind, information=info,
                taps=[1] if kind == "polar" else [1, 0, 1, 1, 0, 1, 1],
                ebn0_db=2.0, initial_llr_mean=4*.5*10**.2, indices="zero-based",
                transform="F tensor log2(N), no bit reversal", ga_means=means)
        for name, pos in patterns[n].items():
            for key in ("punctured", "shortened"):
                path = ROOT / "profiles/matrices" / f"{n}_{name}_{key}.csv"
                with path.open("w", newline="", encoding="utf-8") as f:
                    csv.writer(f).writerows([[int(j == i) for j in range(n)] for i in pos[key]])
    (ROOT / "profiles/ga_2db.json").write_text(json.dumps(fixture, indent=2)+"\n", encoding="utf-8")
    (ROOT / "profiles/rate_matching.json").write_text(json.dumps(patterns, indent=2)+"\n", encoding="utf-8")
    py = '"""Hard-coded fixtures generated by tools/freeze_profiles.py; no runtime GA."""\n'
    py += "INFORMATION = " + repr(information) + "\nPATTERNS = " + repr(patterns) + "\n"
    (ROOT / "python/polar_spectrum/_fixtures.py").write_text(py, encoding="utf-8")
    m = ["function cfg = profile(N, kind)", "% Hard-coded GA@Eb/N0=2 dB; indices converted to MATLAB indexing.",
         "if nargin<2, kind='polar'; end", "switch N"]
    for n, info in information.items():
        m += [f"case {n}", "info0 = ["+" ".join(map(str, info))+"];"]
    m += ["otherwise, error('polar_spectrum:profile','Supported lengths: 64,128,256.');", "end",
          "if ~ismember(string(kind), [\"polar\",\"pac\"]), error('Unknown code kind.'); end",
          "cfg=struct('n',N,'k',N/2,'kind',char(kind),'information',info0+1,'information_zero_based',info0,'ebn0_db',2.0);",
          "cfg.taps=1; if strcmp(kind,'pac'), cfg.taps=[1 0 1 1 0 1 1]; end", "end"]
    (ROOT / "matlab/+polar_spectrum/profile.m").write_text("\n".join(m)+"\n", encoding="utf-8")
    m = ["function [P,S,ET,EP,ES] = rate_matching(N, mode)",
         "% Fixed coordinate-selector matrices; x_tx=x*ET.', ES*x.'=0.",
         "if nargin<2, mode='none'; end", "P=[]; S=[];", "switch N"]
    for n in patterns:
        m += [f"case {n}", "switch char(mode)"]
        for name, pos in patterns[n].items():
            p = " ".join(str(j+1) for j in pos["punctured"])
            s = " ".join(str(j+1) for j in pos["shortened"])
            m += [f"case '{name}'", f"P=[{p}]; S=[{s}];"]
        m += ["otherwise, error('Unknown rate-matching mode.');", "end"]
    m += ["otherwise, error('Supported lengths: 64,128,256.');", "end",
          "E=eye(N); EP=E(P,:); ES=E(S,:); ET=E(setdiff(1:N,[P S]),:);", "end"]
    (ROOT / "matlab/+polar_spectrum/rate_matching.m").write_text("\n".join(m)+"\n", encoding="utf-8")
    print(json.dumps({n:dict(k=len(info), information=info) for n, info in information.items()}, indent=2))


if __name__ == "__main__":
    main()
